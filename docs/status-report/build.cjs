/**
 * Renders docs/status-report/content.cjs into both:
 *   docs/PROJECT-STATUS.md            — reviewable in git diffs
 *   docs/SPIMS-Project-Status.docx    — the client-facing Word document
 *
 * Run after editing content.js:
 *   node docs/status-report/build.cjs
 */

const fs = require('node:fs');
const path = require('node:path');
const {
  AlignmentType,
  BorderStyle,
  Document,
  Footer,
  HeadingLevel,
  PageBreak,
  PageNumber,
  Packer,
  Paragraph,
  ShadingType,
  Table,
  TableCell,
  TableRow,
  TextRun,
  WidthType,
  convertInchesToTwip,
} = require('docx');

const content = require('./content.cjs');
const OUT_DIR = path.resolve(__dirname, '..');

const FONT = 'Poppins';
const NAVY = '111C55';
const ACCENT = 'E31A38';
const MUTED = '6B6E86';
const RULE = 'D9DBE7';
const HEAD_FILL = 'F2F3F8';
const NOTE_FILL = 'F7F4EC';

// A4 usable width: 11906 twips less 1 inch margins each side.
const TABLE_WIDTH = 11906 - convertInchesToTwip(2);

/* ------------------------------------------------------------------ Markdown */

function toMarkdown() {
  const { meta, sections } = content;
  const lines = [
    `# ${meta.title}`,
    '',
    `**${meta.subtitle}**  `,
    `${meta.client} · ${meta.author}  `,
    `Version ${meta.version} · ${meta.date} · build \`${meta.commit}\``,
    '',
    '> Generated from `docs/status-report/content.cjs`. Edit that file and run',
    '> `node docs/status-report/build.cjs` — do not edit this file directly.',
    '',
    '---',
    '',
  ];

  for (const section of sections) {
    lines.push(`## ${section.heading}`, '');
    for (const block of section.blocks) {
      if (block.type === 'h3') {
        lines.push(`### ${block.text}`, '');
      } else if (block.type === 'p') {
        lines.push(block.text, '');
      } else if (block.type === 'note') {
        lines.push(`> ${block.text}`, '');
      } else if (block.type === 'bullets') {
        for (const item of block.items) lines.push(`- ${item}`);
        lines.push('');
      } else if (block.type === 'table') {
        lines.push(`| ${block.head.join(' | ')} |`);
        lines.push(`|${block.head.map(() => '---').join('|')}|`);
        for (const row of block.rows) lines.push(`| ${row.join(' | ')} |`);
        lines.push('');
      }
    }
  }
  return lines.join('\n');
}

/* ---------------------------------------------------------------------- DOCX */

const body = (text, opts = {}) =>
  new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    spacing: { after: 160, line: 300 },
    children: [new TextRun({ text, font: FONT, size: 21, color: '2A2E52', ...opts })],
  });

function cell(text, { header = false, width, bold = false } = {}) {
  return new TableCell({
    width: { size: width, type: WidthType.DXA },
    shading: header ? { type: ShadingType.CLEAR, fill: HEAD_FILL, color: 'auto' } : undefined,
    margins: { top: 100, bottom: 100, left: 130, right: 130 },
    children: [
      new Paragraph({
        alignment: AlignmentType.LEFT,
        spacing: { after: 0, line: 280 },
        children: [
          new TextRun({
            text,
            font: FONT,
            size: 19,
            bold: header || bold,
            color: header ? NAVY : '2A2E52',
          }),
        ],
      }),
    ],
  });
}

function buildTable(block) {
  const columns = block.head.length;
  // First column narrower when it is a short label column.
  const widths =
    columns === 2
      ? [Math.round(TABLE_WIDTH * 0.32), TABLE_WIDTH - Math.round(TABLE_WIDTH * 0.32)]
      : columns === 3
        ? [Math.round(TABLE_WIDTH * 0.38), Math.round(TABLE_WIDTH * 0.42), TABLE_WIDTH - Math.round(TABLE_WIDTH * 0.38) - Math.round(TABLE_WIDTH * 0.42)]
        : Array.from({ length: columns }, () => Math.round(TABLE_WIDTH / columns));

  const border = { style: BorderStyle.SINGLE, size: 2, color: RULE };
  return new Table({
    columnWidths: widths,
    width: { size: TABLE_WIDTH, type: WidthType.DXA },
    borders: { top: border, bottom: border, left: border, right: border, insideHorizontal: border, insideVertical: border },
    rows: [
      new TableRow({
        tableHeader: true,
        children: block.head.map((h, i) => cell(h, { header: true, width: widths[i] })),
      }),
      ...block.rows.map(
        (row) =>
          new TableRow({
            children: row.map((value, i) => cell(value, { width: widths[i], bold: columns === 3 && i === 0 })),
          }),
      ),
    ],
  });
}

function noteBlock(text) {
  return new Table({
    columnWidths: [TABLE_WIDTH],
    width: { size: TABLE_WIDTH, type: WidthType.DXA },
    borders: {
      top: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
      bottom: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
      right: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
      left: { style: BorderStyle.SINGLE, size: 12, color: ACCENT },
      insideHorizontal: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
      insideVertical: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
    },
    rows: [
      new TableRow({
        children: [
          new TableCell({
            width: { size: TABLE_WIDTH, type: WidthType.DXA },
            shading: { type: ShadingType.CLEAR, fill: NOTE_FILL, color: 'auto' },
            margins: { top: 160, bottom: 160, left: 200, right: 200 },
            children: [
              new Paragraph({
                alignment: AlignmentType.JUSTIFIED,
                spacing: { after: 0, line: 300 },
                children: [new TextRun({ text, font: FONT, size: 20, color: '4A3A22' })],
              }),
            ],
          }),
        ],
      }),
    ],
  });
}

function buildDocx() {
  const { meta, sections } = content;

  const cover = [
    new Paragraph({ spacing: { after: 0, before: 2600 }, children: [] }),
    new Paragraph({
      spacing: { after: 120, line: 460, lineRule: 'exact' },
      children: [new TextRun({ text: meta.title, font: FONT, size: 44, bold: true, color: NAVY })],
    }),
    new Paragraph({
      spacing: { after: 420 },
      children: [new TextRun({ text: meta.subtitle, font: FONT, size: 24, color: MUTED })],
    }),
    new Paragraph({
      spacing: { after: 60 },
      children: [new TextRun({ text: meta.client, font: FONT, size: 21, color: '2A2E52' })],
    }),
    new Paragraph({
      spacing: { after: 300 },
      children: [new TextRun({ text: meta.author, font: FONT, size: 21, bold: true, color: NAVY })],
    }),
    new Paragraph({
      spacing: { after: 0 },
      border: { top: { style: BorderStyle.SINGLE, size: 6, color: ACCENT, space: 12 } },
      children: [
        new TextRun({
          text: `Version ${meta.version}  ·  ${meta.date}  ·  build ${meta.commit}`,
          font: FONT,
          size: 18,
          color: MUTED,
        }),
      ],
    }),
  ];

  const main = [];
  sections.forEach((section, index) => {
    main.push(
      new Paragraph({
        heading: HeadingLevel.HEADING_1,
        spacing: { before: index === 0 ? 0 : 380, after: 180 },
        children: [new TextRun({ text: section.heading, font: FONT, size: 28, bold: true, color: NAVY })],
      }),
    );

    for (const block of section.blocks) {
      if (block.type === 'h3') {
        main.push(
          new Paragraph({
            heading: HeadingLevel.HEADING_2,
            spacing: { before: 260, after: 130 },
            children: [new TextRun({ text: block.text, font: FONT, size: 23, bold: true, color: '2B4C9B' })],
          }),
        );
      } else if (block.type === 'p') {
        main.push(body(block.text));
      } else if (block.type === 'note') {
        main.push(noteBlock(block.text));
        main.push(new Paragraph({ spacing: { after: 180 }, children: [] }));
      } else if (block.type === 'bullets') {
        for (const item of block.items) {
          main.push(
            new Paragraph({
              bullet: { level: 0 },
              alignment: AlignmentType.LEFT,
              spacing: { after: 90, line: 290 },
              children: [new TextRun({ text: item, font: FONT, size: 21, color: '2A2E52' })],
            }),
          );
        }
        main.push(new Paragraph({ spacing: { after: 120 }, children: [] }));
      } else if (block.type === 'table') {
        main.push(buildTable(block));
        main.push(new Paragraph({ spacing: { after: 220 }, children: [] }));
      }
    }
  });

  const footer = new Footer({
    children: [
      new Paragraph({
        alignment: AlignmentType.CENTER,
        children: [new TextRun({ children: [PageNumber.CURRENT], font: FONT, size: 17, color: MUTED })],
      }),
    ],
  });

  const page = { margin: { top: 1440, right: 1440, bottom: 1440, left: 1440 } };

  return new Document({
    creator: meta.author,
    title: meta.title,
    description: `${meta.subtitle} — status report v${meta.version}`,
    sections: [
      // Cover carries no page number.
      { properties: { page }, footers: { default: new Footer({ children: [] }) }, children: cover },
      {
        properties: { page: { ...page, pageNumbers: { start: 1 } } },
        footers: { default: footer },
        children: main,
      },
    ],
  });
}

/* --------------------------------------------------------------------- main */

fs.writeFileSync(path.join(OUT_DIR, 'PROJECT-STATUS.md'), toMarkdown() + '\n');
console.log('wrote docs/PROJECT-STATUS.md');

Packer.toBuffer(buildDocx()).then((buf) => {
  fs.writeFileSync(path.join(OUT_DIR, 'SPIMS-Project-Status.docx'), buf);
  console.log(`wrote docs/SPIMS-Project-Status.docx (${(buf.length / 1024).toFixed(0)} KB)`);
});
