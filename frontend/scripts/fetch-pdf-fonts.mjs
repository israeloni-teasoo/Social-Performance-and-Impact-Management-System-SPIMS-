/**
 * Downloads the TrueType files the PDF exporter embeds, and writes them as a base64
 * module.
 *
 * Two families, matching how Seplat's own Social Performance Report is set:
 *
 *   Space Grotesk  headings and headline figures. This is the display face Seplat
 *                  uses, confirmed by reading the font table of their 2025 report.
 *   Poppins        body copy. Seplat set theirs in Aeonik, which is a commercial
 *                  licence we do not hold; Poppins is the closest face we can embed
 *                  and redistribute.
 *
 * The PDF engine embeds fonts rather than referencing them, so exports render
 * identically everywhere and — like the interface — no reader's machine contacts
 * Google. Embedding is also what fixes the naira sign: the previous exporter used the
 * built-in Helvetica encoding, which has no glyph for it, so every currency figure
 * came out corrupted. Neither family here carries a naira glyph either, which is why
 * CURRENCY_FALLBACK below exists and is preserved across regeneration.
 *
 * TrueType rather than woff2 because that is what the PDF format embeds.
 *
 *   node frontend/scripts/fetch-pdf-fonts.mjs
 *
 * The output is committed, so a build needs no network access.
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(HERE, '../src/pdfFonts.ts');

// An older user-agent string makes Google serve TrueType instead of woff2.
const UA = 'Mozilla/4.0';

/** Resolves a Google Fonts family to its TrueType URLs, in the order requested. */
async function faceUrls(family) {
  const css = await fetch(`https://fonts.googleapis.com/css?family=${family}`, {
    headers: { 'User-Agent': UA },
  }).then((r) => r.text());

  const urls = [...css.matchAll(/url\((https:\/\/fonts\.gstatic\.com[^)]+\.ttf)\)/g)].map((m) => m[1]);
  if (urls.length < 2) throw new Error(`${family}: expected two TrueType URLs, found ${urls.length}.`);
  return urls.slice(0, 2);
}

async function download(url) {
  const buf = Buffer.from(await fetch(url, { headers: { 'User-Agent': UA } }).then((r) => r.arrayBuffer()));
  console.log(`  ${(buf.length / 1024).toFixed(0)} KB  ${url.split('/').pop()}`);
  return buf.toString('base64');
}

async function main() {
  const [poppins, grotesk] = await Promise.all([
    faceUrls('Poppins:400,700'),
    faceUrls('Space+Grotesk:500,700'),
  ]);

  const [regular, bold, displayMedium, displayBold] = await Promise.all(
    [...poppins, ...grotesk].map(download),
  );

  const body = `/*
 * Generated by frontend/scripts/fetch-pdf-fonts.mjs — do not edit by hand.
 *
 * TrueType, base64, embedded into exported PDFs so they render identically on any
 * machine and carry the naira sign correctly.
 *
 * Space Grotesk is the display face Seplat's own Social Performance Report is set in;
 * Poppins carries body copy. Both are licensed under the SIL Open Font License 1.1.
 */

export const POPPINS_REGULAR = '${regular}';

export const GROTESK_MEDIUM = '${displayMedium}';

export const GROTESK_BOLD = '${displayBold}';

export const POPPINS_BOLD = '${bold}';
`;

  // Poppins has no naira glyph, so a tiny DejaVu subset is embedded alongside it and
  // used only for the characters Poppins lacks. Regenerate it with:
  //   python3 -c "from fontTools import subset; ..."  (see CURRENCY_FALLBACK in the
  // generated file). It is carried through unchanged here so this script never drops it.
  const existing = await readFile(OUT, 'utf8').catch(() => '');
  const fallback = existing.match(/export const CURRENCY_FALLBACK = '([^']*)'/)?.[1];
  const withFallback = fallback
    ? body.replace("export const POPPINS_BOLD", `export const CURRENCY_FALLBACK = '${fallback}';\n\nexport const POPPINS_BOLD`)
    : body;

  await writeFile(OUT, withFallback);
  if (!fallback) console.warn('  ! CURRENCY_FALLBACK was not preserved — the naira sign will be missing.');
  console.log(`\nwrote ${path.relative(process.cwd(), OUT)} (${(body.length / 1024).toFixed(0)} KB)`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
